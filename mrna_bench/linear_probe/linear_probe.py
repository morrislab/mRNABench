from collections.abc import Callable
from pathlib import Path

import numpy as np
import pandas as pd
import torch
import torch.nn as nn

from sklearn.base import BaseEstimator
from sklearn.linear_model import LinearRegression, LogisticRegressionCV
from sklearn.linear_model import Ridge, RidgeCV
from sklearn.multioutput import MultiOutputClassifier
from sklearn.pipeline import Pipeline, make_pipeline
from sklearn.preprocessing import StandardScaler

from mrna_bench.data_splitter.data_splitter import DataSplitter
from mrna_bench.linear_probe.evaluator import LinearProbeEvaluator
from mrna_bench.persister import ResultsPersister, metrics_by_split


_ACTIVATIONS: dict[str, Callable[[], nn.Module]] = {
    "identity": nn.Identity,
    "sigmoid": nn.Sigmoid,
    "softmax": lambda: nn.Softmax(dim=-1),
}


def to_torch(model: BaseEstimator) -> dict:
    """Convert a fitted linear probe to a torch checkpoint.

    The module rebuilt by LinearProbe.load_checkpoint() returns, with one
    column per output, predict() for regression, the positive class
    probability for binary and multilabel classification, and the per-class
    probabilities (in ``classes`` order) for multiclass classification.

    A leading StandardScaler is folded into the linear layer.

    Args:
        model: Fitted scikit-learn linear model, optionally a pipeline of
            a StandardScaler and a linear model.

    Returns:
        Checkpoint with the linear layer weights, output activation, and
        class labels.
    """
    scaler = None
    if isinstance(model, Pipeline):
        scaler, model = model[0], model[-1]

    if isinstance(model, MultiOutputClassifier):
        estimators = model.estimators_
        activation = "sigmoid"
        classes = None
    else:
        estimators = [model]
        classes = getattr(model, "classes_", None)
        if classes is None:
            activation = "identity"
        else:
            activation = "sigmoid" if len(classes) == 2 else "softmax"

    in_dim = estimators[0].coef_.shape[-1]
    weight = np.concatenate([e.coef_.reshape(-1, in_dim) for e in estimators])
    bias = np.concatenate([np.ravel(e.intercept_) for e in estimators])
    if scaler is not None:
        weight = weight / scaler.scale_
        bias = bias - weight @ scaler.mean_
    return {
        "activation": activation,
        "classes": None if classes is None else classes.tolist(),
        "state_dict": {
            "0.weight": torch.tensor(weight, dtype=torch.float32),
            "0.bias": torch.tensor(bias, dtype=torch.float32),
        },
    }


class LinearProbe:
    """Linear Probe Module.

    Performs linear probing on embeddings for sequences from a benchmark
    dataset generated by an embedding model. The linear probing task can
    be selected at initialization on a target column from the benchmarking
    dataset dataframe.

    The train and test splits for linear probing can be recomputed from random
    seeds. This module supports generating splits based on sequence gene name
    homology from homologene.

    Trained linear probe models for a specific data split can be accessed
    through the models attribute. The linear probe results can be persisted
    to a disk.
    """

    # Penalized probes standardize the embeddings so that one penalty grid
    # suits every model, whatever the scale of its embeddings.
    regression_models = {
        "ols": lambda: LinearRegression(n_jobs=-1),
        "ridge": lambda: make_pipeline(
            StandardScaler(),
            RidgeCV(alphas=np.logspace(-3, 6, 10)),
        ),
    }
    linear_models = {
        "classification": lambda: make_pipeline(
            StandardScaler(),
            LogisticRegressionCV(
                Cs=np.logspace(-5, 2, 8),
                cv=5,
                scoring="neg_log_loss",
                max_iter=5000,
                l1_ratios=(0,),
                use_legacy_attributes=False,
            ),
        ),
        "multilabel": lambda: make_pipeline(
            StandardScaler(),
            MultiOutputClassifier(
                LogisticRegressionCV(
                    Cs=np.logspace(-5, 2, 8),
                    cv=5,
                    scoring="neg_log_loss",
                    max_iter=5000,
                    l1_ratios=(0,),
                    use_legacy_attributes=False,
                ),
                n_jobs=-1,
            ),
        ),
    }

    def __init__(
        self,
        data_df: pd.DataFrame,
        embeddings: np.ndarray,
        target_col: str,
        task: str,
        splitter: DataSplitter,
        evaluator: LinearProbeEvaluator,
        eval_all_splits: bool,
        persister: ResultsPersister | None = None,
        regressor: str = "ridge",
    ):
        """Initialize LinearProbe.

        Args:
            dataset: Dataframe containing sequences to be probed. Dataframe
                should contain target columns and sequences should have the
                same order as the array of embeddings.
            model_short_name: Name of model used to generate embedding.
            embeddings: Embeddings of dataset sequences to be probed.
            target_col: Target column in dataframe for linear probing task.
            task: Linear probing task to perform.
            evaluator: Evaluator object for linear probing results.
            eval_all_splits: Evaluate metrics on all splits. Only evaluates
                validation split otherwise.
            persister: Persister object for linear probing results.
                If not provided, results will not be saved.
            regressor: Regression estimator, either ``ols`` or ``ridge``.
        """
        valid_tasks = {*self.linear_models, "regression"}
        if task not in valid_tasks:
            raise ValueError("Invalid task name.")
        if regressor not in self.regression_models:
            raise ValueError("regressor must be one of ols or ridge.")

        if target_col not in data_df.columns:
            raise ValueError("Target column not found in dataframe.")

        self.data_df = data_df.copy()
        self.data_df["embeddings"] = list(embeddings)

        self.task = task
        self.regressor = regressor
        self.target_col = target_col

        self.splitter = splitter
        self.persister = persister
        self.evaluator = evaluator
        self.eval_all_splits = eval_all_splits

        self.models: dict[int, BaseEstimator] = {}

    def get_df_splits(
        self,
        random_seed: int,
        dropna: bool = True
    ) -> dict[str, np.ndarray]:
        """Get train, validation, and test splits for data and labels.

        Args:
            random_seed: Random seed used for generating data splits.
            dropna: Drop rows with NaN values in target column.

        Returns:
            Dictionary containing per-split data and labels as numpy arrays.
        """
        data_df_copy = self.data_df.copy()

        if dropna:
            data_df_copy = data_df_copy.dropna(subset=[self.target_col])

        train_df, val_df, test_df = self.splitter.get_all_splits_df(
            data_df_copy,
            random_seed=random_seed
        )

        splits = {
            "train_X": np.array(train_df["embeddings"].tolist()),
            "train_y": train_df[self.target_col].to_numpy(),
        }

        if not val_df.empty:
            splits["val_X"] = np.array(val_df["embeddings"].tolist())
            splits["val_y"] = val_df[self.target_col].to_numpy()

        if not test_df.empty:
            splits["test_X"] = np.array(test_df["embeddings"].tolist())
            splits["test_y"] = test_df[self.target_col].to_numpy()

        if isinstance(splits["train_y"][0], np.ndarray):
            splits["train_y"] = np.vstack(list(splits["train_y"]))

            if "val_y" in splits:
                splits["val_y"] = np.vstack(list(splits["val_y"]))
            if "test_y" in splits:
                splits["test_y"] = np.vstack(list(splits["test_y"]))

        return splits

    def run_linear_probe(
        self,
        random_seed: int = 2541,
        persist: bool = False,
        dropna: bool = True,
        save_checkpoint: bool = False,
    ) -> dict[str, float]:
        """Perform data split and run linear probe.

        Args:
            random_seed: Random seed used for data split.
            persist: Save results to disk.
            dropna: Drop rows with NaN values in target column
            save_checkpoint: Also save the fitted probe weights when
                persisting results.

        Returns:
            Dictionary of linear probing metrics per split.
        """
        model = self.make_model(self.task, self.regressor)
        splits = self.get_df_splits(random_seed, dropna)

        np.random.seed(random_seed)
        # sklearn >= 1.9 fits float32 input in float32, which stops L-BFGS
        # early on poorly scaled embeddings.
        train_X = splits["train_X"].astype(np.float64)

        try:
            model.fit(train_X, splits["train_y"])
        except ValueError:
            if self.task == "regression" and self.regressor == "ridge":
                model = Ridge(solver="sag", alpha=1e-3)
                model.fit(train_X, splits["train_y"])
            else:
                raise

        self.models[random_seed] = model

        if self.eval_all_splits:
            eval_splits = splits
        else:
            eval_splits = {
                "val_X": splits["val_X"],
                "val_y": splits["val_y"]
            }

        metrics = self.evaluator.evaluate_linear_probe(model, eval_splits)

        if self.persister and persist:
            self.persister.persist_run_results(
                metrics_by_split(metrics),
                random_seed,
                fit_info=self._fit_info(model, splits),
            )
            if save_checkpoint:
                torch.save(
                    to_torch(model),
                    self.persister.get_checkpoint_path(random_seed),
                )
        elif persist and not self.persister:
            raise RuntimeError("Must provide persister to persist results.")

        return metrics

    @classmethod
    def make_model(cls, task: str, regressor: str = "ridge") -> BaseEstimator:
        """Create the unfitted estimator for a task.

        Args:
            task: Linear probing task.
            regressor: Regression estimator, either ``ols`` or ``ridge``.

        Returns:
            Unfitted scikit-learn estimator.
        """
        if task == "regression":
            return cls.regression_models[regressor]()
        else:
            return cls.linear_models[task]()

    @classmethod
    def get_probe_config(
        cls,
        task: str,
        regressor: str = "ridge",
        feature_view: str | None = None,
        splitter_config: dict | None = None,
    ) -> dict:
        """Get the probe config persisted with results.

        Args:
            task: Linear probing task.
            regressor: Regression estimator, either ``ols`` or ``ridge``.
            feature_view: Feature view of the embeddings probed.
            splitter_config: Data splitter settings, see DataSplitter.config.

        Returns:
            Config holding the estimator's repr, which lists its settings,
            and the feature view and splitter settings when given.
        """
        estimator = repr(cls.make_model(task, regressor))
        config: dict = {"estimator": " ".join(estimator.split())}
        if feature_view is not None:
            config["features"] = feature_view
        if splitter_config:
            config["splitter"] = splitter_config
        return config

    @staticmethod
    def _fit_info(model: BaseEstimator, splits: dict) -> dict:
        """Get split sizes and the regularization chosen when fitting."""
        info: dict = {
            "n_" + name.removesuffix("_y"): len(values)
            for name, values in splits.items() if name.endswith("_y")
        }
        final = model[-1] if isinstance(model, Pipeline) else model
        if isinstance(final, MultiOutputClassifier):
            info["C"] = [float(e.C_) for e in final.estimators_]
        elif hasattr(final, "C_"):
            info["C"] = float(final.C_)
        elif hasattr(final, "alpha_"):
            info["alpha"] = float(final.alpha_)
        elif hasattr(final, "alpha"):
            info["alpha"] = float(final.alpha)
        return info

    def linear_probe_multirun(
        self,
        random_seeds: list[int],
        persist: bool = False
    ) -> dict[int, dict[str, float]]:
        """Run one linear probe per random seed.

        Args:
            random_seeds: Random seeds used to generate dataset splits.
            persist: Save each run to the configured persister.

        Returns:
            Metrics for each random seed.
        """
        return {
            random_seed: self.run_linear_probe(random_seed, persist)
            for random_seed in random_seeds
        }

    def compute_multirun_results(
        self,
        metrics: dict[int, dict[str, float]],
        print_output: bool = False,
        ci_multiplier: float = 1.96,
    ) -> dict[str, str]:
        """Aggregate multi-run linear probing results.

        Prints mean metric and confidence interval at desired level.

        Args:
            metrics: Result of multi-run linear probing.
            print_output: Prints aggregated metrics.
            ci_multiplier: Constant multiplied to standard error to get CI.

        Returns:
            Dictionary of mean metric and CI per data split.
        """
        metric_vals: dict[str, list[float]] = {}

        for metric_dict in metrics.values():
            for metric_name, metric_val in metric_dict.items():
                metric_vals.setdefault(metric_name, []).append(metric_val)

        metric_mean = {k: np.mean(v) for k, v in metric_vals.items()}
        metric_std = {k: np.std(v) for k, v in metric_vals.items()}

        metric_out = {}

        for k in metric_vals.keys():
            se = ci_multiplier * (metric_std[k] / (np.sqrt(len(metrics))))
            metric_out[k] = "{} ± {}".format(metric_mean[k], se)

            if print_output:
                print("{} ± {}".format(metric_mean[k], se))

        return metric_out

    def get_fit_model(self, random_seed: int) -> BaseEstimator:
        """Return the model trained for a specific split seed.

        Args:
            random_seed: Random seed identifying the fitted split.

        Returns:
            Estimator fitted for the requested seed.
        """
        return self.models[random_seed]

    @staticmethod
    def load_checkpoint(path: str | Path) -> nn.Module:
        """Load a linear probe saved with its results as a torch module.

        Args:
            path: Checkpoint path, see ResultsPersister.

        Returns:
            Module mapping embeddings (N, H) to predictions; see to_torch().
        """
        checkpoint = torch.load(path)
        out_dim, in_dim = checkpoint["state_dict"]["0.weight"].shape
        module = nn.Sequential(
            nn.Linear(in_dim, out_dim),
            _ACTIVATIONS[checkpoint["activation"]](),
        )
        module.load_state_dict(checkpoint["state_dict"])
        return module.eval()
